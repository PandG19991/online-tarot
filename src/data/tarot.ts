export function getMajorArcana(): TarotCard[] {
  return [...majorArcana, ...majorArcanaPart2];
}

export function getMinorArcana(suit?: string): TarotCard[] {
  const minor = [...wands, ...cups, ...swords, ...pentacles];
  if (suit) {
    return minor.filter((card) => card.suit === suit);
  }
  return minor;
}

